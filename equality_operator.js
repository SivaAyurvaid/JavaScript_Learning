
console.log('Double Equality (==)');
console.log('Comparing number 5 and number 5',5 == 5);
console.log('Comparing number 5 and number 6',5 == 6);
console.log('Comparing String 5 and number 5',5 == '5');
console.log('Comparing String 5 and number 6',5 == '6');
console.log('Comparing Boolean false and number 0',false == 0);
console.log('Comparing Boolean true and number 1',true == 1);
console.log('Comparing Boolean true and number 2',true == 2);
console.log('Comparing null and undefined',null == undefined);
console.log('Comparing Empty string and number 0',"" == 0);
console.log('Comparing Empty array and Empty string',[] == "");


